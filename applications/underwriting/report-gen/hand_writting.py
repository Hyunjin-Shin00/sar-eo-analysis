# ══ ② 비교분석 2건 — demo_cmp/ ════════════════════════════════════════════
def make_cmp(addresses=CMP_ADDRS, *, root=CMP_DIR, yard=True, refresh_yard=False,
             pdf=False, fresh=False, verbose=True):
    """두 촬영일 비교분석 — 값(t1·t2) · 비교 그림 · HTML. **PDF 는 손판이라 안 덮는다.**

    `fresh=True` 면 날짜분 결과(`t1`·`t2` 의 `demo.json`)를 **다시 낸다.** 기본은 재사용인데,
    그러면 **손보정을 고쳐도 값이 안 따라온다** — 실측 2026-08-25: 신당동 대장 동 이름을
    `ledger_rename` 으로 바꿨는데 저장된 결과를 그대로 써서 종이가 그대로였다. 야적 판독은
    캐시(`_yard.json`)를 그대로 쓰므로 다시 내도 VLM 을 부르지 않는다.
    """
    fail = []
    for i, address in enumerate(addresses, 1):
        if verbose:
            print(f"\n{'=' * 70}\n[{i}/{len(addresses)}] {address}  (비교분석)\n{'=' * 70}")
        h = hand(address)
        stem = str(Path(root) / f"위성_비교분석_{slug(address)}")
        Path(stem).parent.mkdir(parents=True, exist_ok=True)
        try:
            for f in CMP.build(address, stem, scene1=SCENE1, scene2=SCENE2,
                               t1_root=Path(root) / "t1", t2_root=Path(root) / "t2",
                               skip=h.road_side, hand=h, yard=yard,
                               refresh_yard=refresh_yard, fresh=fresh, pdf=pdf,
                               verbose=verbose):
                print(f"  → {f}  ({f.stat().st_size / 1024:,.0f} KB)")
        except Exception as e:                               # noqa: BLE001
            fail.append((address, f"{type(e).__name__}: {e}"))
            print(f"  실패 — {fail[-1][1]}"[:200])
    for address, why in fail:
        print(f"[실패] {address} — {why}"[:200])
    return len(addresses) - len(fail), fail


