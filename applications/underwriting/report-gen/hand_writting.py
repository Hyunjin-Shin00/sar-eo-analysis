# 다섯 부가 다 같이 하는 것 셋 — 표 맞추기 · **본문 그림** 갈아 끼우기(`RF.swap`) ·
# **머리글 로고** 갈아 끼우기(`RF.swap_logo`). 로고는 `assets/brand/client_logo.png` 하나를
# 보고, 그 파일은 화면 렌더러([[sitecheck/report/single.py]] `LOGO`)도 같이 본다 — 종이와
# 화면이 다른 로고를 달면 같은 물건이 두 얼굴로 나간다.
#
# 각 함수는 `(pdf 경로, 볼 것 목록)` 을 돌려주고, `check` 가 참이면 고치지 않고 목록만 낸다.

# 손판을 맞출 **대상 폴더**. 기본은 데모(`demo/`)이고, `--model` 이면 모델 경로 산출물
# (`out/`)을 본다 — 판짜기는 같은 손판을 쓰고 값만 그쪽에서 뽑는다. 아래 세 함수와
# `RF.swap` 의 그림 폴더가 이 둘을 같이 본다.
_ROOT_NAME, _JSON_NAME = "demo", "demo.json"


def _demo_pdf(address):
    return f"{_ROOT_NAME}/{slug(address)}/보고서.pdf"


def _demo_json(address):
    return f"{_ROOT_NAME}/{slug(address)}/{_JSON_NAME}"


def _demo_html(address):
    return f"{_ROOT_NAME}/{slug(address)}/보고서.html"


def _page1(fx, r):
    """1면 — 「본 물건 분석 결과」 세 줄과 상단 「확인 필요 항목」을 값에서 다시 쓴다.

    2면 표만 맞추던 때에는 이 세 줄이 손으로 적힌 채 남아, 같은 물건의 종이와 화면이 다른
    말을 했다(실측 2026-08-26 고잔동: 종이 「서측 … 최소 이격 1.5 m · 8건」, 화면 「북서 …
    0.0 m · 10건」). 줄 수는 늘 셋이라 아래를 밀 일이 없다.
    """
    rows, cols = RF.result_rows(r)
    t = fx.tables[0][-1]
    if RF.fit_table(fx, t, rows, colors=cols):
        raise SystemExit("1면 결과 표 줄 수가 바뀌었다 — 아래 덩어리를 밀어야 한다")
    RF.overview_line(fx, r)
    RF.set_check(fx, r, _near(r))


def _near(r):
    n = (r.get("context") or {}).get("buildings_near") or {"features": []}
    return n["features"] if isinstance(n, dict) else n


def horim(check):
    """호림동 — A동 표 · B동 표 두 벌. B동 표가 늘면 쪽 아래로 늘린다.

    **B동 표 아래에는 아무것도 없다** — 각주도 없고 다음 줄도 없어서(2면은 이 표로 끝난다)
    늘어난 만큼 아래로 내밀면 된다. 쪽 바닥 글(y 810.5)까지 자리가 남아 있고, 1면 표는
    y 803 까지 내려가 있으므로 이 판이 허용하는 범위 안이다.
    """
    pdf = _demo_pdf(호림동)
    by = RF.sep_by_dong(RF.load(_demo_json(호림동)))
    fx = PR.Refit(str(ROOT / pdf))
    ta, tb = fx.tables[1]
    plan = [(f"p2 A동 표 {len(ta.row_tops)}→{len(by['A동'])}줄", ta.rows_text, by["A동"]),
            (f"p2 B동 표 {len(tb.row_tops)}→{len(by['B동'])}줄", tb.rows_text, by["B동"])]
    if check:
        return pdf, plan

    dy = RF.fit_table(fx, ta, by["A동"])
    if dy:
        # A동 표가 늘거나 줄면 아래 덩어리(■ B동 소제목 + B동 표)를 그만큼 밀어야 한다.
        # 지금 값에서는 그럴 일이 없으므로 그 길은 만들어 두지 않고 여기서 멈춘다 —
        # 안 밀고 지나가면 표가 소제목을 덮는다.
        raise SystemExit(f"A동 표 줄 수가 바뀌었다({dy:+.1f} pt) — 아래 덩어리를 밀어야 한다")
    RF.fit_table(fx, tb, by["B동"])
    _page1(fx, RF.load(_demo_json(호림동)))
    RF.swap(fx, f"{_ROOT_NAME}/{slug(호림동)}/report")
    RF.fix_legends(fx, ROOT / _demo_html(호림동))   # 범례를 화면과 맞춘다
    RF.swap_logo(fx)          # 머리글 로고 — 자산은 assets/brand/client_logo.png
    RF.swap_bar(fx)           # 전폭 남색 띠 → 로고 폭 밑줄(샘플 신판 형식)
    RF.blue_bullets(fx)       # 절 제목의 ■ 만 같은 파랑으로
    RF.drop_overview_rows(fx)  # 1면 개요의 「분석 방법」·「적재 구역 출처」 칸을 뺀다
    fx.save()
    return pdf, plan


