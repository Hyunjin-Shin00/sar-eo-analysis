def cmp_sindang(check):
    """신당동 비교 — 야적이 뒤집혀 있었고(1차 1개소→2차 0개소), 판독 면적이 1 ㎡ 컸다."""
    pdf, t1, t2, figs = _cmp_paths(신당동)
    y1, c1 = RF.yard_rows(t1)
    y2, c2 = RF.yard_rows(t2)
    fx = PR.Refit(str(ROOT / pdf))
    ty1, ty2 = fx.tables[2]
    plan = [(f"p2 A동 표 {len(fx.tables[1][0].row_tops)}→{len(RF.cmp_rows(t1, t2)['A동'][0])}줄",
             fx.tables[1][0].rows_text, [r[:2] + [RF.flat(r[2]), RF.flat(r[3]), r[4]]
                                         for r in RF.cmp_rows(t1, t2)["A동"][0]]),
            (f"p2 B동 표 {len(fx.tables[1][1].row_tops)}→{len(RF.cmp_rows(t1, t2)['B동'][0])}줄",
             fx.tables[1][1].rows_text, [r[:2] + [RF.flat(r[2]), RF.flat(r[3]), r[4]]
                                         for r in RF.cmp_rows(t1, t2)["B동"][0]]),
            ("p1 개요·변화표 판독 면적 1,466 → 1,465 ㎡", ["1,466 ㎡"], ["1,465 ㎡"]),
            ("p1 야적 구역 수", [ty1.rows_text and "1개소 → 0개소 (-1개소)"], ["0개소 → 2개소 (+2개소)"]),
            (f"p3 1차 적재표 {len(ty1.row_tops)}→{len(y1)}줄", ty1.rows_text, y1),
            (f"p3 2차 적재표 {len(ty2.row_tops)}→{len(y2)}줄", ty2.rows_text, y2),
            ("p4 대장표 A동 862 → 861 ㎡ · 합계 1,466 → 1,465 ㎡", ["862 ㎡", "+19 ㎡ (+2 %)"],
             ["861 ㎡", "+18 ㎡ (+2 %)"]),
            ("p4 대장 동 이름을 판독 동에 맞춘다", ["C동", "A동"], ["A동", "B동"])]
    if check:
        return pdf, plan

    # 1면 — 개요 한 줄 + 변화표 두 칸
    RF.once(fx, 0, "1,466 ㎡", "1,465 ㎡", count=3)
    # **야적 세 칸은 한 덩어리로 한 번만 뒤집는다.** 낱개로 「있으면 고친다」를 걸 수 없다 —
    # 앞 칸을 0개소 로 바꾼 뒤에는 「0개소」가 두 칸이 되어, 다시 돌리면 뒤 칸 대신 앞 칸을
    # 잡는다. 그래서 아직 안 고친 판에만 있는 「-1개소」를 표지로 삼는다.
    if RF.has(fx, 0, "-1개소"):
        fx.edit_line(0, "1개소", "0개소", where=lambda t: t.strip() == "1개소")
        fx.edit_line(0, "0개소", "2개소", where=lambda t: t.strip() == "0개소")
        fx.edit_line(0, "-1개소", "+2개소")
    # 2면 — 이격 변화 표 두 벌(A동 · B동). **번호가 값에서 나오므로 여기도 맞춘다** —
    # 안 맞추면 갈아 끼운 그림의 배지와 종이의 번호가 갈린다(실측 2026-08-26).
    by = RF.cmp_rows(t1, t2)
    for t, (rows, cols) in zip(fx.tables[1], (by["A동"], by["B동"])):
        if RF.fit_table(fx, t, rows, colors=cols):
            raise SystemExit("2면 표 줄 수가 바뀌었다 — 아래 덩어리를 밀어야 한다")
    # 3면 — 두 시기의 적재 구역 표
    for t, rows, cols in ((ty1, y1, c1), (ty2, y2, c2)):
        RF.fit_table(fx, t, rows, colors=cols)
    # 4면 — 대장 표(1차·2차 두 벌)
    RF.once(fx, 3, "862 ㎡", "861 ㎡", count=2)
    RF.once(fx, 3, "+19 ㎡ (+2 %)", "+18 ㎡ (+2 %)", count=2)
    RF.once(fx, 3, "1,466 ㎡", "1,465 ㎡", count=2)
    RF.once(fx, 3, "+23 ㎡ (+2 %)", "+22 ㎡ (+2 %)", count=2)
    # 대장 동 이름 — **「대장 동」 열만**(x 101 쯤). 「판독 동」 열(x 61)에도 A동 이 있어
    # 글자로만 찾으면 그쪽을 잡는다. 값 쪽은 `ledger_rename` 이 이미 바꿔 두었다.
    RF.retext(fx, 3, {"C동": "A동", "A동": "B동"}, xrange=(95, 125), only_if="C동")
    RF.swap(fx, figs, RF.CMP_FIGS)
    RF.fix_legends(fx, ROOT / pdf.replace('.pdf', '.html'))   # 범례를 화면과 맞춘다
    RF.swap_logo(fx)          # 머리글 로고 — 자산은 assets/brand/client_logo.png
    RF.swap_bar(fx)           # 전폭 남색 띠 → 로고 폭 밑줄(샘플 신판 형식)
