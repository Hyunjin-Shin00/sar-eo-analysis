# ── 비교분석 손판을 모델 값으로 ────────────────────────────────────────────
def _rgb(h):
    """`#7c3aed` → (r, g, b) 0~1. 화면 렌더러는 hex 로, 종이 쪽은 튜플로 색을 쓴다."""
    if not isinstance(h, str) or not h.startswith("#"):
        return None
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def _cell(c):
    """`build_doc` 의 칸 → (글자, 색). 칸은 문자열이거나 (글자, 색) 이거나 조각 목록이다."""
    if isinstance(c, str):
        return c, None
    if isinstance(c, (tuple, list)) and len(c) == 2 and all(isinstance(x, str) for x in c):
        return c[0], _rgb(c[1])
    return RF.flat(c), None


def _head_off(fx, t):
    """표 머리행의 글자 기준선 — 위쪽 경계선에서 몇 pt 아래인가. **지우기 전에** 재야 한다."""
    sp = PR._spans(fx.doc[t.page], t.head_top, t.head_bot)
    return round(sp[0]["origin"][1] - t.head_top, 3) if sp else t.base_off


def _move_table(fx, page_no, t, rows, colors, dy, hoff):
    """표와 그 소제목을 `dy` 만큼 내려 **통째로 다시 그린다**.

    옮기는 것이 아니라 다시 그리는 이유는 표의 테두리가 글자가 아니라 **칠한 사각형**이라
    `move_spans` 로는 안 따라오기 때문이다. 지우고 `render_table` 로 새 자리에 그린다.
    """
    page = fx.doc[page_no]
    x0 = min(c.x0 for c in t.cols)
    x1 = max(c.x1 for c in t.cols)
    # 절 소제목(표 머리 위)과 **머리행 글자**를 지우기 전에 담아 둔다.
    heads = [sp for txt, sp in fx.lines(page_no)
             if sp and t.head_top - 24 < sp[0]["origin"][1] < t.head_top and txt.strip()]
    # **머리행은 다시 앉히지 않고 있는 것을 그대로 옮긴다.** 두 줄짜리 머리(「1차\n(2026-06-18)」)
    # 를 한 줄로 다시 쓰면 조각이 뒤섞인다(실측 2026-08-27: 「1차 (202618)-06-」). 정렬도
    # 본문과 달라(가운데) 다시 계산할 이유가 없다 — [[pdf_refit.head_spans]] 가 그래서 있다.
    hspans = fx.head_spans(t)
    fx.erase(page, (x0 - 40, t.head_top - 24, x1 + 40, t.bottom + 3))
    for sp in heads:
        fx.move_spans(page_no, sp, dy, erase=False)
    fx.render_table(page_no, t.cols, t.head_top + dy, [""] * len(t.cols), rows,
                    row_h=t.row_h, head_h=t.head_bot - t.head_top,
                    base_off=t.base_off, head_off=hoff, colors=colors)
    if hspans:
        fx.move_spans(page_no, hspans, dy, erase=False)


def _fit_stack(fx, page_no, want, *, verbose=True):
    """한 면에 **세로로 쌓인 표들**을 지금 값에 맞춘다 — 늘면 아래를 그만큼 내린다.

    **표를 손보지 않고 통째로 다시 그린다.** 제자리 수선(`fit_table`)은 줄 수가 그대로일 때는
    깔끔하지만, 줄이 늘거나 탐지가 놓친 행에 쓸 때 **테두리가 반쯤 남는다** — 실측
    2026-08-27: 대장표 「합계」 행이 아래 선 없이 잘려 나갔고, 이격 표의 는 줄이 표 밖에
    걸쳤다. 다시 그리면 그런 자리가 없다(테두리·칸 배경·글자를 한 번에 낸다).
    **아래에서부터** 처리한다 — 위 표를 먼저 옮기면 아직 안 옮긴 아래 표를 덮는다.

    `horim` 이 「그 길은 만들어 두지 않고 여기서 멈춘다」고 적어 둔 그 길이다. 데모에서는
    줄 수가 안 변해 필요가 없었는데, 모델 값으로 바꾸면 변한다(실측 신당동 2면 5·4 → 6·5줄).
    """
    tabs = fx.tables.get(page_no, [])
    if len(tabs) != len(want):
        if verbose:
            print(f"  p{page_no + 1}: 표 수가 다르다 {len(tabs)} vs {len(want)} — 건너뛴다")
        return
    R = [[[_cell(c)[0] for c in r] for r in w[1][1:]] for w in want]
    C = [[[_cell(c)[1] for c in r] for r in w[1][1:]] for w in want]
    # **탐지가 놓친 마지막 줄을 되찾는다.** 대장표의 「합계」 줄은 칸 배경이 달라
    # `find_tables` 가 본문 행으로 세지 않는다(검출 2줄 · 실제 3줄). 그대로 두면 늘어난
    # 것으로 오인해 아래를 밀어 버려 옛 줄과 새 줄이 겹친다(실측 2026-08-27 4면).
    for t, r in zip(tabs, R):
        if len(r) == len(t.row_tops) + 1 and PR._spans(fx.doc[page_no], t.bottom + 1,
                                                       t.bottom + t.row_h - 1):
            t.row_tops.append(t.bottom)
    grow = [len(r) - len(t.row_tops) for t, r in zip(tabs, R)]
    hoffs = [_head_off(fx, t) for t in tabs]          # **지우기 전에** 재 둔다
    for i in range(len(tabs) - 1, -1, -1):
        dy = sum(grow[:i]) * tabs[i].row_h
        _move_table(fx, page_no, tabs[i], R[i], C[i], dy, hoffs[i])
        if verbose and (dy or grow[i]):
            print(f"  p{page_no + 1} 표{i + 1}: {len(tabs[i].row_tops)}→{len(R[i])}줄"
                  + (f" · {dy:+.1f} pt 내림" if dy else ""))


def cmp_model(address, check=False):
    """비교분석 손판 한 부를 **모델 값**으로 맞춘다.

    `cmp_sindang`·`cmp_hosan` 과 하는 일은 같지만 값을 글자로 박지 않는다 — 그 둘은 데모의
    특정 값을 겨눈 일회용 패치(`RF.once(fx, 0, "1,466 ㎡", "1,465 ㎡")`)라 다른 물건에 못
    쓴다. 여기서는 표를 전부 [[report/compare.py]] `build_doc` 이 내는 줄로 채운다 —
    화면 보고서와 **같은 함수**라 종이와 화면이 갈릴 수 없다.
    """
    stem = f"위성_비교분석_{slug(address)}"
    src, dst = ROOT / "demo_cmp" / f"{stem}.pdf", ROOT / "out_cmp" / f"{stem}.pdf"
    if not src.exists():
        raise SystemExit(f"손판이 없다: {src}")
    t1 = RF.load(f"out_cmp/t1/{slug(address)}/result.json")
    t2 = RF.load(f"out_cmp/t2/{slug(address)}/result.json")
    figdir = ROOT / "out_cmp" / f"{stem}_이미지"
    im = lambda d: {k: str(figdir / d / n) for k, n in                       # noqa: E731
                    (("sep", "1_이격거리.png"), ("yard", "2_야적물.png"),
                     ("led", "3_미등록증축.png"))}
    doc = CMP.build_doc(t1, t2, im("1차"), im("2차"))
    plan = [(f"p{i + 1} 표 {len([b for b in pg['blocks'] if b[0] == 'tbl'])}벌", [], [])
            for i, pg in enumerate(doc)]
    if check:
        return f"out_cmp/{stem}.pdf", plan

    import shutil
    shutil.copy2(src, dst)                      # **손판을 본으로 삼는다**
    fx = PR.Refit(str(dst))
    # 1면 「물건 개요」 두 줄 — 대장 줄과 판독 건물 줄. 표지는 「용도」의 유무다.
    d1 = dict(FR.overview_rows(t1, FR._ledger_view(t1),
                               DR.dong_names(t1["layers"]["buildings"])))
    for key, has_use in (("건축물대장", True), ("위성 판독 건물", False)):
        want = (d1.get(key) or "").replace("  ·  ", " \xa0·\xa0 ").replace("   (", " \xa0(")
        for txt, _sp in list(fx.lines(0)):
            cur = txt.strip()
            if want and "건축면적 합계" in cur and ("용도" in cur) == has_use and cur != want:
                fx.edit_line(0, cur, want)
                break
    # 1면은 표를 **이름으로 찾는다.** 「물건 개요」가 여러 개의 한 줄짜리 표로 잡혀
    # (`find_tables`) 문서 쪽 표 수와 안 맞으므로, 고칠 것 하나만 집어 낸다.
    chg = next((t for t in fx.tables.get(0, [])
                if t.rows_text and "이격거리(필지 내" in (t.rows_text[0][0] or "")), None)
    want1 = [b for b in doc[0]["blocks"] if b[0] == "tbl"]
    if chg is not None and want1:
        rows = [[_cell(c)[0] for c in r] for r in want1[-1][1][1:]]
        cols = [[_cell(c)[1] for c in r] for r in want1[-1][1][1:]]
        # 1면 변화탐지 표 **아래에는 아무것도 없다**(쪽 밑 글줄까지 자리가 남는다). 그래서
        # 줄이 늘어도 밀 것이 없고, 통째로 다시 그리면 된다 — 제자리 수선은 는 줄이 표
        # 밖에 걸친다(실측 2026-08-27 호산동 1면: 「철거 또는 판독 누락」이 아래 줄과 겹쳤다).
        _move_table(fx, 0, chg, rows, cols, 0.0, _head_off(fx, chg))
    for i in range(1, len(doc)):
        _fit_stack(fx, i, [b for b in doc[i]["blocks"] if b[0] == "tbl"])
    RF.swap(fx, f"out_cmp/{stem}_이미지", RF.CMP_FIGS)
    RF.fix_legends(fx, ROOT / f"out_cmp/{stem}.html")
    RF.swap_logo(fx)
    RF.swap_bar(fx)
    RF.blue_bullets(fx)
    fx.save()
    return f"out_cmp/{stem}.pdf", plan


def make_refit_model(*, check=False, only=None):
    """**모델 경로 산출물(`out/`)의 PDF 를 손판에 맞춘다.**

    왜 필요한가. `run.py` 가 내는 PDF 는 [[sitecheck/report/single.py]] 가 matplotlib 으로
    그린 판이고, 저장소에 든 데모 PDF 는 **Chrome 으로 인쇄한 손판**이다. 둘은 같은 mm
    상수에서 나오지만 판짜기가 다르다 — 실측 2026-08-27(호림동 2면): 지도 88 mm 대 129 mm ·
    표 행 높이 10.2 mm 대 7.6 mm. 값과 줄 수를 다 맞춰도 이 차이는 남는다.
    (HTML 은 다르다 — 두 길이 **같은 렌더러**를 쓰므로 CSS 가 바이트까지 같고, 이제 지도
    크기까지 같다. 판이 갈리는 것은 PDF 뿐이다.)

    그래서 데모가 쓰는 그 방법을 그대로 쓴다: **손판을 본으로 삼아 값·그림만 갈아 끼운다.**
    데모 PDF 를 `out/<주소>/보고서.pdf` 로 복사한 뒤 같은 refit 함수를 모델 값으로 돌린다 —
    `_page1`·`RF.sep_by_dong`·`RF.fit_table` 은 전부 값에서 뽑아 쓰므로 주소별 손질이 없다.

    **대가 둘.** ① `out/` 의 PDF 는 이제 `run.py` 만으로는 안 나온다(데모 PDF 가 본으로
    있어야 한다). ② 데모에 손판이 있는 세 주소에만 걸린다. 그래서 파이프라인에 넣지 않고
    사람이 따로 부르는 자리에 둔다 — `python hand_writting.py --only refit --model`.

    비교분석(`out_cmp/`)은 아직 안 한다 — `cmp_*` 함수가 1면 개요값을 글자로 박아 고치는데
    (`RF.once(fx, 0, "1,466 ㎡", "1,465 ㎡")`) 그 값이 데모 전용이라, 모델 값으로 바꾸려면
    그 자리마다 새로 적어야 한다.
    """
    import shutil
    global _ROOT_NAME, _JSON_NAME
    # **돌릴 것만 복사한다.** `--one` 으로 하나만 고칠 때 나머지까지 본판으로 덮으면 그
    # 부들은 데모 값을 그대로 인 채로 남는다(실측 2026-08-27: `--one cmp_model` 이 단일시점
    # 세 부를 본판으로 되돌려 놓았다).
    todo = [a for a, fn in zip(DEMO, ("horim", "hosan", "gojan")) if not only or only == fn]
    for address in todo:
        src = ROOT / "demo" / slug(address) / "보고서.pdf"
        dst = ROOT / "out" / slug(address) / "보고서.pdf"
        if not src.exists():
            raise SystemExit(f"손판이 없다: {src} — 본으로 삼을 판이 있어야 한다")
        if not dst.parent.exists():
            raise SystemExit(f"모델 산출물이 없다: {dst.parent} — run.py 를 먼저 돌리세요")
        # **`--check` 에도 복사한다.** refit 은 손판의 표 상자를 찾아 고치는 도구라,
        # matplotlib 이 그린 판 위에서는 표를 하나도 못 찾는다(`fx.tables[1]` 이 빈다).
        # 지워지는 것은 `run.py` 가 언제든 다시 뽑는 판이다.
        shutil.copy2(src, dst)              # **손판을 본으로 삼는다**(값은 아래에서 갈아 낀다)
        print(f"· 손판을 본으로 복사 {src.parent.name}/보고서.pdf → out/ "
              f"(matplotlib 판을 덮었다 — run.py 로 되돌릴 수 있다)")
    _ROOT_NAME, _JSON_NAME = "out", "result.json"
    try:
        make_refit(check=check, only=only, group=(horim, hosan, gojan))
    finally:
        _ROOT_NAME, _JSON_NAME = "demo", "demo.json"
    for address in CMP_ADDRS:                   # 비교분석 2건 — 표를 build_doc 에서 채운다
        if only and only != "cmp_model":
            continue
        pdf, _plan = cmp_model(address, check)
        print(("· 볼 것 " if check else "· 고침 ") + pdf)


def make_refit(*, check=False, only=None, group=None):
    for fn in (group or REFIT):
        if only and fn.__name__ != only:
            continue
        pdf, plan = fn(check)
        print(("· 볼 것 " if check else "· 고침 ") + pdf)
        for title, was, now in plan:
            print(f"    {title}")
            if was != now:
                for x in was:
                    print(f"        전 {x}")
                for x in now:
                    print(f"        후 {x}")


