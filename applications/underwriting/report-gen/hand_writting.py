def main(argv=None):
    ap = argparse.ArgumentParser(
        description="손으로 정한 데모 산출물 5건 — demo/ 3건 + demo_cmp/ 2건")
    ap.add_argument("--only", choices=("demo", "cmp", "refit"),
                    help="이 묶음만 (기본은 셋 다)")
    ap.add_argument("--model", action="store_true",
                    help="`--only refit` 과 함께 — 데모가 아니라 **모델 경로 산출물**"
                         "(`out/`)의 PDF 를 손판에 맞춘다(단일시점 3건)")
    ap.add_argument("--one", help="PDF 맞추기에서 함수 하나만 (horim · hosan · gojan · "
                                  "cmp_hosan · cmp_sindang)")
    ap.add_argument("--check", action="store_true",
                    help="PDF 를 고치지 않고 어긋난 데만 적는다")
    ap.add_argument("--verify", action="store_true",
                    help="고친 PDF 를 다시 읽어 우리 값과 대조한다")
    ap.add_argument("--no-yard", action="store_true", help="VLM 판독을 건너뛴다(비용)")
    ap.add_argument("--refresh-yard", action="store_true",
                    help="저장된 야적 판독을 버리고 다시 부른다(유료)")
    ap.add_argument("--fresh", action="store_true",
                    help="비교분석의 날짜분 결과를 재사용하지 않고 다시 낸다 — **손보정을 고쳤으면 "
                         "이것을 줘야 값이 따라온다**(야적 판독 캐시는 그대로 쓴다)")
    ap.add_argument("--quiet", action="store_true")
    a = ap.parse_args(argv)

    if a.verify:
        return 1 if RF.verify(REFIT, VERIFY_FIGS) else 0

    kw = dict(yard=not a.no_yard, refresh_yard=a.refresh_yard, verbose=not a.quiet)
    # **모델 경로 산출물의 종이만 맞추는 길** — 데모 값은 건드리지 않는다.
    if a.model:
        if a.only not in (None, "refit"):
            ap.error("--model 은 `--only refit` 과 함께만 쓴다")
        make_refit_model(check=a.check, only=a.one)
        return 0
    if a.only in (None, "demo"):
        make_demo(**kw)
    if a.only in (None, "cmp"):
        make_cmp(fresh=a.fresh, **kw)
    if a.only in (None, "refit"):
        # 값이 바뀌었으면 종이의 표도 따라와야 한다 — **PDF 안의 글자·그림만** 갈아 끼운다.
        make_refit(check=a.check, only=a.one)
    return 0


if __name__ == "__main__":
    sys.exit(main())
