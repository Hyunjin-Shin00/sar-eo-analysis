def ledger_verdict(measured_m2, ledger_m2, attached=None):
    """실측 건축면적 vs 대장 건축면적 → 판정.

    ledger_m2 가 None 이면 대장에 대응하는 동이 없다는 뜻 — 붙었는지 떨어졌는지로
    증축의심/미등록의심을 가른다.
    """
    if ledger_m2 is None:
        if measured_m2 < LEDGER_MIN_BLD_M2:
            return {"level": "이상없음", "label": "대상 아님",
                    "reason": (f"실측 {measured_m2:.0f} ㎡ — 건물 최소면적 "
                               f"{LEDGER_MIN_BLD_M2:.0f} ㎡ 미만"),
                    "basis": None}
        # 부착 여부를 **모르는 것**과 떨어져 있다고 **확인한 것**은 다르다. 등록 footprint 가
        # 없거나 신뢰도 미달이면 붙었는지 알 수 없는데, 그때 '별동'이라고 쓰면 확인하지 않은
        # 것을 확인한 것처럼 내게 된다.
        if attached is None:
            return {"level": "주의", "label": "대장 미반영 · 부착 여부 미상",
                    "reason": (f"대장에 대응하는 동이 없다 · 실측 {measured_m2:.0f} ㎡ · "
                               f"등록 기하가 없어 증축(부착)인지 별동인지 가를 수 없다"),
                    "basis": "건축법 시행령 제2조(증축)"}
        kind = "증축의심(부착)" if attached else "미등록의심(별동)"
        where = "등록 건물에 붙어 있다" if attached else "등록 건물과 떨어져 있다"
        return {"level": "경고", "label": kind,
                "reason": f"대장에 대응하는 동이 없다 · 실측 {measured_m2:.0f} ㎡ · {where}",
                "basis": "건축법 시행령 제2조(증축)"}

    over = measured_m2 - ledger_m2
    ratio = measured_m2 / ledger_m2 if ledger_m2 else float("inf")
    basis = "건축법 제14조 제1항 제1호"
    if over < LEDGER_EXT_MIN_M2 or ratio < LEDGER_EXT_RATIO:
        return {"level": "이상없음", "label": "대장과 일치",
                "reason": (f"대장 {ledger_m2:.0f} ㎡ · 실측 {measured_m2:.0f} ㎡ · "
                           f"초과 {over:+.0f} ㎡({(ratio-1)*100:+.0f} %) — "
                           f"모델 면적오차({LEDGER_MODEL_AREA_ERR*100:.0f} %)와 구분되지 않는다"),
                "basis": basis}
    if over < LEDGER_PERMIT_M2:
        return {"level": "주의", "label": "증축",
                "reason": (f"대장 {ledger_m2:.0f} ㎡ · 실측 {measured_m2:.0f} ㎡ · "
                           f"초과 {over:+.0f} ㎡ — 건축신고로 할 수 있는 규모"),
                "basis": basis}
    return {"level": "경고", "label": "증축 · 현장 확인 대상",
            "reason": (f"대장 {ledger_m2:.0f} ㎡ · 실측 {measured_m2:.0f} ㎡ · "
                       f"초과 {over:+.0f} ㎡ — 신고 한도 {LEDGER_PERMIT_M2:.0f} ㎡ 이상"),
            "basis": basis}


