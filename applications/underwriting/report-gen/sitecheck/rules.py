FIRE_DETOUR = 1.35           # 주행거리 ÷ 직선거리 가정(도로 우회율)
# 7분 × 35 km/h = 4.1 km 주행 → 직선 약 3.0 km. 여기까지가 「7분 안쪽으로 볼 수 있는」 범위.
FIRE_SAFE_KM = round(FIRE_GOLDEN_MIN / 60 * FIRE_SPEED_KMH / FIRE_DETOUR, 1)
FIRE_WARN_KM = FIRE_SAFE_KM * 2      # 그 두 배 밖은 7분에 못 갈 쪽으로 본다
FIRE_BASIS = ("소방청 「화재현장 7분 도착」 관리지표를 직선거리로 환산한 값 "
              f"(주행 {FIRE_SPEED_KMH} km/h · 우회율 {FIRE_DETOUR} 가정)")


def fire_access_verdict(dist_m):
    """최근접 소방관서까지의 **직선거리** → 3단계. 주행거리가 아니다."""
    if dist_m is None:
        return "판정 불가"
    km = dist_m / 1000.0
    if km <= FIRE_SAFE_KM:
        return "안전"
    return "주의" if km <= FIRE_WARN_KM else "위험"


CLIMATE_TOP_RISK = 0.10      # 전국 상위 10 % 안 → 위험
CLIMATE_TOP_WARN = 0.25      # 상위 25 % 안 → 주의
CLIMATE_BASIS = (f"전국 ASOS 지점 순위 — 상위 {CLIMATE_TOP_RISK:.0%} 안 위험 · "
                 f"{CLIMATE_TOP_WARN:.0%} 안 주의 (법정 기준이 아니라 모집단 위치다)")


def climate_rank_verdict(rank, pop):
    """전국 순위 → 3단계. `rank` 1위가 가장 센 곳이다."""
    if not rank or not pop:
        return "판정 불가"
    q = rank / pop
    if q <= CLIMATE_TOP_RISK:
        return "위험"
    return "주의" if q <= CLIMATE_TOP_WARN else "안전"


WIND_CODE_WARN = 0.80        # 법정 기본풍속의 80 % 이상이면 주의
WIND_CODE_BASIS = "「건축물의 구조기준 등에 관한 규칙」 별표 5 지역별 기본풍속"


def wind_code_verdict(obs_ms, code_ms):
    """관측 최대풍속 ↔ 법정 기본풍속. **10분 평균 계열끼리만 견준다** — 최대순간풍속(돌풍)은
    평균시간이 달라(10분 평균의 1.5배 안팎) 이 함수에 넣지 않는다."""
    if not obs_ms or not code_ms:
        return "판정 불가"
    r = obs_ms / code_ms
    if r > 1.0:
        return "위험"
    return "주의" if r >= WIND_CODE_WARN else "안전"


